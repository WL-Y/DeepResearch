"""General research prompts with contracts compatible with the current pipeline."""
import json

def render_prompt(template: str, **values) -> str:
    """Serialize values once; delimiter escaping is not an injection guarantee.

    Literal JSON in templates must use doubled braces for str.format.
    """
    encoded = {
        key: json.dumps(value, ensure_ascii=False).replace('<', r'\u003c').replace('>', r'\u003e')
        for key, value in values.items()
    }
    return template.format(**encoded)


